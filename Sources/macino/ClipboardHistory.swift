import AppKit
import SwiftUI

struct ClipboardEntry: Identifiable {
    let id = UUID()
    let text: String
    let date = Date()
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published var enabled: Bool {
        didSet {
            defaults.set(enabled, forKey: "clipboardHistoryEnabled")
            configure()
        }
    }
    private let defaults: UserDefaults
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChange = 0
    init(defaults: UserDefaults = .standard, pasteboard: NSPasteboard = .general) {
        self.defaults = defaults
        self.pasteboard = pasteboard
        enabled = defaults.bool(forKey: "clipboardHistoryEnabled")
        configure()
    }
    private func configure() {
        timer?.invalidate(); timer = nil
        lastChange = pasteboard.changeCount
        if !enabled { entries.removeAll(); return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }
    func poll() {
        guard enabled, pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let protected = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        guard !protected.contains(where: { pasteboard.types?.contains(NSPasteboard.PasteboardType($0)) == true }),
              let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= 100_000 else { return }
        entries.removeAll { $0.text == text }
        entries.insert(ClipboardEntry(text: text), at: 0)
        if entries.count > 50 { entries.removeLast(entries.count - 50) }
    }
    func copy(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        lastChange = pasteboard.changeCount
    }
    func remove(_ entry: ClipboardEntry) { entries.removeAll { $0.id == entry.id } }
    func clear() { entries.removeAll() }
}

struct ClipboardHistoryView: View {
    @ObservedObject var history: ClipboardHistory
    @ObservedObject private var shortcut = ClipboardQuickPanel.shared
    @State private var search = ""
    @State private var copied: UUID?
    private var filtered: [ClipboardEntry] {
        history.entries.filter { search.isEmpty || $0.text.localizedCaseInsensitiveContains(search) }
    }
    var body: some View {
        VStack(spacing: 12) {
            HStack {
                Label("Clipboard history", systemImage: "doc.on.clipboard").font(.headline)
                Spacer()
                InfoButton(title: "Clipboard history", text: "Keep your last 50 copied texts here while macino is running. Nothing is saved to disk or sent anywhere. Turning history off or quitting clears the list. Passwords marked private by their app are skipped, but other sensitive text may still appear. Text only, up to 100 KB per item.")
                Toggle("Enabled", isOn: $history.enabled).toggleStyle(.switch).controlSize(.small)
            }
            HStack {
                Toggle("Keyboard shortcut", isOn: $shortcut.enabled).toggleStyle(.checkbox)
                Spacer()
                InfoButton(title: "Quick clipboard", text: "Choose a shortcut to open your clipboard while typing. The default is ⌃V (Control + V). Accessibility access lets macino find the text cursor and paste for you. Without it, the list opens near your mouse and copies the item; press ⌘V to paste.")
            }
            if shortcut.enabled {
                HStack {
                    Button(shortcut.recording ? "Press keys…" : shortcut.shortcutLabel) { shortcut.startRecording() }
                        .help("Click, then press the shortcut you want")
                    if shortcut.recording {
                        Button("Cancel") { shortcut.stopRecording(); shortcut.configure(prompt: false) }
                    } else {
                        Button("Use ⌃V") { shortcut.useSuggestedShortcut() }.buttonStyle(.borderless)
                    }
                    Spacer()
                }
                if !shortcut.shortcutStatus.isEmpty { Text(shortcut.shortcutStatus).font(.caption).foregroundStyle(.secondary) }
            }
            if shortcut.enabled && !history.enabled {
                Text("Turn on history to use the shortcut.").font(.caption).foregroundStyle(.secondary)
            }
            if history.enabled {
                HStack {
                    TextField("Search copied text…", text: $search).textFieldStyle(.roundedBorder)
                    Text("\(history.entries.count) / 50").font(.caption).foregroundStyle(.secondary)
                    Button("Clear all", role: .destructive) { history.clear() }.disabled(history.entries.isEmpty)
                }
                if filtered.isEmpty {
                    VStack(spacing: 8) {
                        Image(systemName: "doc.on.clipboard").font(.largeTitle).foregroundStyle(.teal)
                        Text(history.entries.isEmpty ? "Nothing copied yet" : "No matching items").foregroundStyle(.secondary)
                        Text("⌘C to copy · ⌘V to paste").font(.caption).foregroundStyle(.secondary)
                    }.frame(maxWidth: .infinity).frame(height: 180)
                } else {
                    LazyVStack(spacing: 8) {
                        ForEach(filtered) { entry in
                            HStack(alignment: .top, spacing: 10) {
                                Button { history.copy(entry); copied = entry.id } label: {
                                    VStack(alignment: .leading, spacing: 6) {
                                        Text(entry.text).font(.system(size: 12)).lineLimit(3).multilineTextAlignment(.leading)
                                        HStack {
                                            Text(entry.date, style: .time)
                                            Spacer()
                                            Label(copied == entry.id ? "Copied" : "Copy", systemImage: copied == entry.id ? "checkmark" : "doc.on.doc")
                                        }.font(.caption2).foregroundStyle(.secondary)
                                    }.frame(maxWidth: .infinity, alignment: .leading).contentShape(Rectangle())
                                }.buttonStyle(.plain).help("Copy this text to the clipboard")
                                Button { history.remove(entry) } label: { Image(systemName: "xmark") }.buttonStyle(.borderless).help("Remove from history")
                            }.padding(12).background(.primary.opacity(0.04), in: RoundedRectangle(cornerRadius: 12))
                        }
                    }
                }
            } else {
                VStack(spacing: 9) {
                    Image(systemName: "clipboard").font(.system(size: 32, weight: .light)).foregroundStyle(.secondary)
                    Text("Clipboard history is off").font(.headline)
                    Text("Enable it to remember copied text while macino is running.").font(.caption).foregroundStyle(.secondary)
                }.frame(maxWidth: .infinity).frame(height: 180)
            }
        }
        .task {
            while !Task.isCancelled {
                shortcut.refreshAccess()
                do { try await Task.sleep(for: .seconds(2)) } catch { break }
            }
        }
        .onDisappear { shortcut.stopRecording(); shortcut.configure(prompt: false) }
    }
}
